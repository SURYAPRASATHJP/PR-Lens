"""The Phase 2 query set: a hunk a human reviewed, and the comment they left on it.

The pairs come from the raw review-comment payloads, fetched through the Phase 1 client
with the same listing parameters so the Phase 1 cache answers them. Not from the corpus
units: the miner needs in_reply_to_id, created_at, the PR author and the merge state, and
none of those are in unit metadata. Adding them would change content_hash for every
review_comment unit and re-upload every review_comment shard on the next mine run.

Every comment is kept or dropped by the first rule that fires, and the count per rule is
logged. The counts are findings in their own right: a repo whose comments are mostly nits
is telling Phase 7 something about where a reviewer is missing.
"""

import asyncio
import gzip
import hashlib
import io
import json
import logging
import re
import statistics
from collections import Counter, defaultdict
from collections.abc import Collection, Iterable, Mapping, Sequence
from dataclasses import asdict, dataclass, field
from typing import Any, Literal

from pr_lens.github.client import GitHubClient, NotFound
from pr_lens.ingest.mine import LISTING_MAX_AGE, MiningLimits
from pr_lens.ingest.units import unit_id_for

logger = logging.getLogger(__name__)

MAX_PAIRS_PER_PR = 3
MIN_BODY_CHARS = 40

BOT_LOGINS = frozenset(
    {
        "codecov",
        "coderabbitai",
        "dependabot",
        "pre-commit-ci",
        "sonarcloud",
        "sonarqubecloud",
    }
)

# Accounts of type User whose review comments are generated by a tool. The name-based
# rules above cannot see these, so they are listed as they turn up in the mining data,
# each with the date and repo where it was found.
AUTOMATED_REVIEWERS = frozenset(
    {
        "kramlipi",  # 12 Sep 2026, fastapi/typer: templated "**Worth a look** · design ·"
    }
)

# An acknowledgement followed by less than MIN_BODY_CHARS of anything else is a nit. A
# comment that opens with "Nice, but" and then raises a real problem is not, which is why
# this strips the opener and measures what is left rather than matching the opener alone.
ACKNOWLEDGEMENTS = (
    "lgtm",
    "+1",
    "nice",
    "thanks",
    "thank you",
    "done",
    "fixed",
    "ship it",
    "good catch",
    "looks good",
)

_ACKNOWLEDGEMENT = re.compile(
    r"^\W*(?:" + "|".join(re.escape(a) for a in ACKNOWLEDGEMENTS) + r")\b\W*", re.IGNORECASE
)
_WORD_CHARACTER = re.compile(r"\w")
_SUGGESTION = re.compile(r"^```\s*suggestion\b", re.MULTILINE)

DropReason = Literal[
    "no_path_or_hunk",
    "reply",
    "bot",
    "emoji_only",
    "acknowledgement",
    "short",
    "empty_before_state",
    "body_quotes_hunk",
    "gold_not_in_corpus",
    "not_merged",
    "self_review",
    "per_pr_cap",
    "per_repo_cap",
]


# Two queries per pair, measured on the same pairs. "before" is the spec's rule: the hunk's
# pre-image, context and removed lines only. "reviewed" is the diff_hunk exactly as the
# reviewer saw it. They differ because a review comment's diff_hunk is frozen at the commit
# the comment was made on and ends at the commented line, which is almost always an added
# line: the + lines are the code under review, not a later fix. Checked on live payloads
# 12 Sep 2026. The table reports both so the difference is a number.
QueryVariant = Literal["before", "reviewed"]
QUERY_VARIANTS: tuple[QueryVariant, ...] = ("before", "reviewed")


@dataclass(frozen=True, slots=True)
class ReviewPair:
    """One test case. The query is built from the hunk; the gold is the comment's unit."""

    repo: str
    comment_id: int
    pull_request: int
    path: str
    diff_hunk: str
    body: str
    author: str
    created_at: str
    html_url: str

    @property
    def gold_unit_id(self) -> str:
        return unit_id_for(self.repo, "review_comment", f"review_comment/{self.comment_id}")

    @property
    def before_query(self) -> str:
        return before_state(self.diff_hunk)

    @property
    def reviewed_query(self) -> str:
        return self.diff_hunk

    @property
    def has_suggestion(self) -> bool:
        """A suggestion block carries code, so its gold overlaps the hunk lexically."""
        return bool(_SUGGESTION.search(self.body))

    def as_record(self) -> dict[str, Any]:
        return asdict(self)


@dataclass(slots=True)
class RepoPairs:
    repo: str
    seen: int = 0
    pairs: list[ReviewPair] = field(default_factory=list)
    dropped: Counter[str] = field(default_factory=Counter)


@dataclass(frozen=True, slots=True)
class PullFacts:
    merged: bool
    author: str


def query_text(pair: ReviewPair, variant: QueryVariant) -> str:
    return pair.before_query if variant == "before" else pair.reviewed_query


def before_state(diff_hunk: str) -> str:
    """The hunk's pre-image: context and removed lines, markers stripped, additions gone.

    The @@ line is dropped except for its section heading, which git takes from the
    pre-image and which often names the enclosing function.
    """
    kept = []
    for line in diff_hunk.splitlines():
        if line.startswith("@@"):
            heading = line.split("@@", 2)[-1].strip()
            if heading:
                kept.append(heading)
        elif line.startswith(("+", "\\")):
            continue
        elif line.startswith(("-", " ")):
            kept.append(line[1:])
        else:
            kept.append(line)
    text = "\n".join(kept)
    return text if text.strip() else ""


def nit_reason(body: str) -> DropReason | None:
    stripped = body.strip()
    if not _WORD_CHARACTER.search(stripped) and not stripped.startswith("+1"):
        return "emoji_only"
    remainder = _ACKNOWLEDGEMENT.sub("", stripped, count=1)
    if remainder != stripped and len(remainder.strip()) < MIN_BODY_CHARS:
        return "acknowledgement"
    if len(stripped) < MIN_BODY_CHARS:
        return "short"
    return None


def is_bot(user: object) -> bool:
    if not isinstance(user, dict):
        return True
    login = str(user.get("login", "")).lower()
    return (
        user.get("type") == "Bot"
        or login.endswith("[bot]")
        or login in BOT_LOGINS
        or login in AUTOMATED_REVIEWERS
    )


def screen_comment(comment: Mapping[str, Any]) -> DropReason | ReviewPair:
    """The rules that need nothing but the comment itself. Cheap, so they run first."""
    path = comment.get("path")
    diff_hunk = comment.get("diff_hunk")
    if not isinstance(path, str) or not path or not isinstance(diff_hunk, str):
        return "no_path_or_hunk"
    if not diff_hunk.strip():
        return "no_path_or_hunk"
    if comment.get("in_reply_to_id") is not None:
        return "reply"
    if is_bot(comment.get("user")):
        return "bot"
    body = comment.get("body")
    if not isinstance(body, str):
        return "short"
    nit = nit_reason(body)
    if nit is not None:
        return nit
    if not before_state(diff_hunk):
        # An all-addition hunk, typically a new file. The spec's before-state query is
        # empty for these, so they cannot be scored on the same pairs as the rest.
        return "empty_before_state"
    if before_state(diff_hunk) in body or diff_hunk.strip() in body:
        # The body-only gold would contain its own query, which is the leakage the body-only
        # index exists to remove. Rare, and dropped here so that the harness's leakage
        # assertion stays an invariant rather than a filter.
        return "body_quotes_hunk"
    user = comment.get("user")
    return ReviewPair(
        repo="",
        comment_id=int(comment["id"]),
        pull_request=_pr_number(comment.get("pull_request_url")),
        path=path,
        diff_hunk=diff_hunk,
        body=body,
        author=str(user.get("login", "")) if isinstance(user, dict) else "",
        created_at=str(comment.get("created_at", "")),
        html_url=str(comment.get("html_url", "")),
    )


def apply_pull_facts(
    candidates: Iterable[ReviewPair], facts: Mapping[int, PullFacts], result: RepoPairs
) -> list[ReviewPair]:
    kept = []
    for pair in candidates:
        pull = facts.get(pair.pull_request)
        if pull is None or not pull.merged:
            result.dropped["not_merged"] += 1
        elif pull.author.lower() == pair.author.lower():
            result.dropped["self_review"] += 1
        else:
            kept.append(pair)
    return kept


def cap_per_pr(pairs: Sequence[ReviewPair], result: RepoPairs) -> list[ReviewPair]:
    """One heavily reviewed PR is one conversation, not many independent test cases.

    The earliest comments on a PR are kept, because they were made against the code as
    first proposed rather than against a revision that already absorbed earlier review.
    """
    by_pr: dict[int, list[ReviewPair]] = defaultdict(list)
    for pair in pairs:
        by_pr[pair.pull_request].append(pair)
    kept = []
    for pr_pairs in by_pr.values():
        pr_pairs.sort(key=lambda p: p.comment_id)
        kept.extend(pr_pairs[:MAX_PAIRS_PER_PR])
        if len(pr_pairs) > MAX_PAIRS_PER_PR:
            result.dropped["per_pr_cap"] += len(pr_pairs) - MAX_PAIRS_PER_PR
    return sorted(kept, key=lambda p: p.comment_id)


def cap_per_repo(results: Sequence[RepoPairs]) -> int:
    """Cap every repo at the median repo's surviving count, in place, and return the cap.

    Review velocity across the mining set spans two orders of magnitude, and uncapped the
    query set is mostly two repos. Which pairs survive the cap is decided by a hash of the
    comment id: a stable sample that neither favours recent comments nor moves between
    runs.
    """
    counts = [len(r.pairs) for r in results]
    if not counts:
        return 0
    cap = int(statistics.median(counts))
    for result in results:
        if len(result.pairs) > cap:
            ranked = sorted(result.pairs, key=lambda p: _stable_rank(p.comment_id))
            result.dropped["per_repo_cap"] += len(result.pairs) - cap
            result.pairs = sorted(ranked[:cap], key=lambda p: p.comment_id)
    return cap


async def mine_repo_pairs(
    client: GitHubClient,
    repo: str,
    corpus_comment_units: Collection[str],
    limits: MiningLimits,
) -> RepoPairs:
    """Every rule except the per-repo cap, which needs every repo's count first."""
    result = RepoPairs(repo=repo)
    candidates: list[ReviewPair] = []
    async for comment in client.paginate(
        f"/repos/{repo}/pulls/comments",
        params={"sort": "created", "direction": "desc"},
        max_items=limits.review_comments,
        max_age=LISTING_MAX_AGE,
    ):
        result.seen += 1
        screened = screen_comment(comment)
        if isinstance(screened, str):
            result.dropped[screened] += 1
            continue
        pair = _with_repo(screened, repo)
        if pair.gold_unit_id not in corpus_comment_units:
            # Newer than the corpus snapshot, or empty-bodied when it was mined. A pair
            # whose gold is not indexed can only ever score zero.
            result.dropped["gold_not_in_corpus"] += 1
            continue
        candidates.append(pair)

    facts = await pull_facts(client, repo, {p.pull_request for p in candidates}, limits)
    result.pairs = cap_per_pr(apply_pull_facts(candidates, facts, result), result)
    logger.info(
        "%s: %s comments, %s pairs before the repo cap, dropped %s",
        repo,
        result.seen,
        len(result.pairs),
        dict(sorted(result.dropped.items())),
    )
    return result


async def pull_facts(
    client: GitHubClient, repo: str, numbers: Collection[int], limits: MiningLimits
) -> dict[int, PullFacts]:
    """Merge state and author for each PR, from the Phase 1 listing where it has them.

    The listing is the same request Phase 1 made, so it is a cache hit. Only PRs outside
    that window cost a request each, and those are bounded by the concurrency gate in the
    client rather than fired all at once.
    """
    facts: dict[int, PullFacts] = {}
    async for pr in client.paginate(
        f"/repos/{repo}/pulls",
        params={"state": "closed", "sort": "updated", "direction": "desc"},
        max_items=limits.pull_requests,
        max_age=LISTING_MAX_AGE,
    ):
        number = int(pr["number"])
        if number in numbers:
            facts[number] = _facts(pr)

    async def one(number: int) -> tuple[int, PullFacts | None]:
        try:
            pr = await client.get_json(f"/repos/{repo}/pulls/{number}", max_age=LISTING_MAX_AGE)
        except NotFound:
            return number, None
        return number, _facts(pr)

    missing = sorted(set(numbers) - set(facts))
    for number, fact in await asyncio.gather(*(one(n) for n in missing)):
        if fact is not None:
            facts[number] = fact
    return facts


def _facts(pr: Mapping[str, Any]) -> PullFacts:
    user = pr.get("user")
    return PullFacts(
        merged=bool(pr.get("merged_at")),
        author=str(user.get("login", "")) if isinstance(user, dict) else "",
    )


def _with_repo(pair: ReviewPair, repo: str) -> ReviewPair:
    return ReviewPair(**{**pair.as_record(), "repo": repo})


def _stable_rank(comment_id: int) -> str:
    return hashlib.sha256(str(comment_id).encode()).hexdigest()


def _pr_number(url: object) -> int:
    tail = url.rsplit("/", 1)[-1] if isinstance(url, str) else ""
    return int(tail) if tail.isdigit() else 0


def pairs_path(version: str) -> str:
    return f"eval/pairs/{version}.jsonl.gz"


def manifest_path(version: str) -> str:
    return f"eval/pairs/{version}.json"


def encode_pairs(pairs: Sequence[ReviewPair]) -> bytes:
    """Deterministic bytes: sorted rows, sorted keys, and a gzip header with no clock in it."""
    ordered = sorted(pairs, key=lambda p: (p.repo.lower(), p.comment_id))
    lines = "".join(
        json.dumps(p.as_record(), sort_keys=True, ensure_ascii=False) + "\n" for p in ordered
    )
    buffer = io.BytesIO()
    with gzip.GzipFile(fileobj=buffer, mode="wb", mtime=0) as handle:
        handle.write(lines.encode("utf-8"))
    return buffer.getvalue()


def decode_pairs(payload: bytes) -> list[ReviewPair]:
    return [
        ReviewPair(**json.loads(line)) for line in gzip.decompress(payload).decode().splitlines()
    ]


def digest(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()
